#!/usr/bin/env python3
"""
SCORING FILE — LOCKED. Do not edit this file.
Scores the quality of Eric's second brain vault.
Returns a single number: 0-100 (higher = better).
"""

import os
import re
import json
from pathlib import Path

VAULT = Path("/home/eric/workspaces/second-brain")
SKIP_DIRS = {"auto-research", ".git", ".obsidian"}

def get_all_notes():
    notes = []
    for f in VAULT.rglob("*.md"):
        if any(part in SKIP_DIRS for part in f.parts):
            continue
        notes.append(f)
    return notes

def score_vault():
    notes = get_all_notes()
    if not notes:
        return 0, {}

    total = len(notes)
    issues = []
    score = 100

    # 1. Frontmatter completeness (-1 per note missing frontmatter)
    missing_frontmatter = []
    for note in notes:
        content = note.read_text(encoding="utf-8", errors="ignore")
        if not content.startswith("---"):
            missing_frontmatter.append(str(note.relative_to(VAULT)))
    deduct = len(missing_frontmatter)
    score -= deduct
    if missing_frontmatter:
        issues.append(f"Missing frontmatter ({deduct}): {missing_frontmatter[:5]}")

    # 2. Wikilinks — find broken [[links]] (-2 per broken link)
    all_note_names = {f.stem.lower() for f in notes}
    broken_links = []
    for note in notes:
        content = note.read_text(encoding="utf-8", errors="ignore")
        links = re.findall(r'\[\[([^\]]+)\]\]', content)
        for link in links:
            link_target = link.split("|")[0].split("#")[0].strip().lower()
            if link_target and link_target not in all_note_names:
                broken_links.append(f"{note.stem} → [[{link}]]")
    deduct = min(len(broken_links) * 2, 20)
    score -= deduct
    if broken_links:
        issues.append(f"Broken wikilinks ({len(broken_links)}): {broken_links[:3]}")

    # 3. Stub notes — notes under 100 chars of content (-1 per stub)
    stubs = []
    for note in notes:
        content = note.read_text(encoding="utf-8", errors="ignore")
        # strip frontmatter
        body = re.sub(r'^---.*?---', '', content, flags=re.DOTALL).strip()
        if len(body) < 100:
            stubs.append(str(note.relative_to(VAULT)))
    deduct = min(len(stubs), 15)
    score -= deduct
    if stubs:
        issues.append(f"Stub notes under 100 chars ({len(stubs)}): {stubs[:5]}")

    # 4. Notes missing Related Notes section (-0.5 per note, capped at 10)
    missing_related = []
    for note in notes:
        content = note.read_text(encoding="utf-8", errors="ignore")
        if "## Related" not in content and "## related" not in content.lower():
            missing_related.append(note.stem)
    deduct = min(int(len(missing_related) * 0.5), 10)
    score -= deduct
    if missing_related:
        issues.append(f"Missing Related Notes section ({len(missing_related)}): {missing_related[:5]}")

    # 5. Bonus: wiki/index.md exists and links to major sections (+5)
    index = VAULT / "wiki" / "index.md"
    if index.exists() and len(index.read_text()) > 200:
        score += 5

    score = max(0, min(100, score))

    return score, {
        "total_notes": total,
        "missing_frontmatter": len(missing_frontmatter),
        "broken_wikilinks": len(broken_links),
        "stub_notes": len(stubs),
        "missing_related_sections": len(missing_related),
        "issues": issues,
        "score": score
    }

if __name__ == "__main__":
    score, details = score_vault()
    print(f"SCORE: {score}/100")
    for k, v in details.items():
        if k != "issues":
            print(f"  {k}: {v}")
    if details.get("issues"):
        print("  Issues:")
        for issue in details["issues"]:
            print(f"    - {issue}")
